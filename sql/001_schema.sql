-- Safe to rerun on the existing schema; this does not recreate or truncate tables.
CREATE TABLE IF NOT EXISTS car_listings (
    listing_id TEXT PRIMARY KEY,
    vehicle_id TEXT NOT NULL,
    make TEXT NOT NULL,
    model TEXT NOT NULL,
    model_year INTEGER NOT NULL,
    listing_price NUMERIC(14, 2) CHECK (listing_price > 0),
    odometer_km BIGINT NOT NULL CHECK (odometer_km >= 0),
    sale_status TEXT NOT NULL,
    sale_date DATE,
    completed_sale_price NUMERIC(14, 2) CHECK (completed_sale_price > 0),
    CHECK (sale_status IN ('Available', 'Pending', 'Reserved', 'Sold', 'Withdrawn')),
    CHECK (sale_status <> 'Sold' OR sale_date IS NOT NULL),
    CHECK (sale_status = 'Sold' OR completed_sale_price IS NULL)
);

CREATE TABLE IF NOT EXISTS dim_vehicle_model (
    vehicle_model_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    make TEXT NOT NULL,
    model TEXT NOT NULL,
    model_year INTEGER NOT NULL,
    UNIQUE (make, model, model_year)
);

CREATE TABLE IF NOT EXISTS dim_listing_status (
    status_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_status TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS fact_car_listing (
    listing_id TEXT PRIMARY KEY,
    vehicle_id TEXT NOT NULL,
    vehicle_model_key BIGINT NOT NULL REFERENCES dim_vehicle_model(vehicle_model_key),
    status_key BIGINT NOT NULL REFERENCES dim_listing_status(status_key),
    listing_price NUMERIC(14, 2) CHECK (listing_price > 0),
    completed_sale_price NUMERIC(14, 2) CHECK (completed_sale_price > 0),
    odometer_km BIGINT NOT NULL CHECK (odometer_km >= 0),
    sale_date DATE
);

CREATE TABLE IF NOT EXISTS pipeline_batches (
    batch_id UUID PRIMARY KEY,
    source_file TEXT NOT NULL,
    source_sha256 TEXT NOT NULL,
    source_rows BIGINT NOT NULL,
    started_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finished_at TIMESTAMPTZ,
    status TEXT NOT NULL CHECK (status IN ('RUNNING', 'SUCCESS', 'FAILED')),
    failed_step TEXT
);
